/**
 * 職業文字列から汎用カテゴリを自動推定する。
 * 優先度順に部分一致を探し、最初にマッチしたカテゴリを返す。
 * どれにも当てはまらなければ「その他」。
 */
export function categorizeOccupation(occupation: string): OccupationCategory {
  const text = occupation.toLowerCase().trim();
  if (!text) return "その他";

  for (const { category, keywords } of KEYWORD_RULES) {
    if (keywords.some((kw) => text.includes(kw.toLowerCase()))) {
      return category;
    }
  }
  return "その他";
}
